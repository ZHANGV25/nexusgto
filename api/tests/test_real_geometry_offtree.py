"""Strict current-street sizing tests for real-geometry live resolve."""

from __future__ import annotations

from dataclasses import replace

import pytest

from app.engine.agent.game_state import GameState, new_postflop_state
from app.engine.agent.offtree_add import (
    SKIP_ADDED_SIZE_CAP,
    OffTreeExactUnsupported,
    _builder_amount,
    build_offtree_extension,
)


def _two_player_state() -> GameState:
    return new_postflop_state(
        seats=["BB", "UTG"],
        preflop_prefix=[2, 0, 0, 0, 0, 1],
        board=[10, 20, 30],
    )


def _synthetic_state(
    history: tuple[int, ...],
    events: tuple[tuple[int, int, int, int, int], ...],
) -> GameState:
    return replace(
        _two_player_state(),
        postflop_history=history,
        street_history=history,
        street_offtree_raises=events,
    )


def test_strict_planner_uses_zero_chip_duplicate_tolerance() -> None:
    state = _synthetic_state((1,), ((0, 751, 1000, 0, 10_000),))

    production = build_offtree_extension(state, (0.75,), (1.0,))
    exact = build_offtree_extension(
        state, (0.75,), (1.0,), strict=True,
    )

    assert production is not None
    assert production.plan is None
    assert exact is not None
    assert exact.plan is not None
    fraction = exact.plan.event_fractions[0]
    assert _builder_amount(fraction, 1000, 0) == 751
    assert exact.plan.added_first == pytest.approx((fraction,))
    assert exact.plan.event_amounts == {0: 751}


def test_real_geometry_records_on_tree_raise_for_native_amount_check() -> None:
    state = replace(_two_player_state(), real_geometry=True)

    observed = state.advance_observed("raise", amount=450)

    assert observed.off_tree is False
    assert observed.state.street_offtree_raises == (
        (0, 450, 600, 0, 9725),
    )
    analysis = build_offtree_extension(
        observed.state, (0.75,), (1.0,), strict=True,
    )
    assert analysis is not None
    assert analysis.plan is not None
    assert analysis.plan.event_amounts == {0: 450}


@pytest.mark.parametrize(
    ("increment", "pot_before", "stack_before"),
    (
        (6000, 1000, 10_000),  # More than five pots, but not all-in.
        (900, 1000, 900),      # Implicit all-in generated by a size clamp.
    ),
)
def test_strict_planner_accepts_exact_large_and_allin_sizes(
    increment: int,
    pot_before: int,
    stack_before: int,
) -> None:
    state = _synthetic_state(
        (1,), ((0, increment, pot_before, 0, stack_before),),
    )

    analysis = build_offtree_extension(
        state, (0.75,), (1.0,), strict=True,
    )

    assert analysis is not None
    assert analysis.plan is not None
    fraction = analysis.plan.event_fractions[0]
    assert min(
        _builder_amount(fraction, pot_before, 0), stack_before,
    ) == increment


def test_strict_planner_fails_when_added_size_cap_loses_event() -> None:
    state = _synthetic_state(
        (1, 2, 2, 2, 2),
        (
            (1, 1200, 1000, 0, 10_000),
            (2, 1300, 1000, 0, 10_000),
            (3, 1400, 1000, 0, 10_000),
            (4, 1500, 1000, 0, 10_000),
        ),
    )

    with pytest.raises(OffTreeExactUnsupported) as exc_info:
        build_offtree_extension(
            state, (0.75,), (1.0,), strict=True,
        )

    assert exc_info.value.skip.step == 4
    assert exc_info.value.skip.reason == SKIP_ADDED_SIZE_CAP


class _AnyStrategyRow(dict):
    def get(self, key, default=None):
        return {"Fold": 0.2, "Call": 0.5, "Raise 100%": 0.3}


class _CaptureEngine:
    def __init__(self, *, unsafe_extension: bool = False) -> None:
        self.calls: list[dict] = []
        self.unsafe_extension = unsafe_extension
        self._last_solve_stats: dict = {}

    def solve(self, **kwargs):
        from app.engine.cpu_es_solver import OffTreeExtensionUnsafe

        self.calls.append(kwargs)
        if self.unsafe_extension and "offtree" in kwargs["hero_replay"]:
            raise OffTreeExtensionUnsafe("synthetic exact extension failure")
        return {
            0: _AnyStrategyRow(),
            1: _AnyStrategyRow(),
        }


def _source(engine: _CaptureEngine):
    from app.engine.agent.modes import ModeConfig
    from app.engine.agent.strategy_source import LiveResolveSource

    return LiveResolveSource(
        ModeConfig(mode="LIVE_RESOLVE"),
        cpu_es_solver=engine,
        seed_ranges=False,
        belief_carry=False,
        offtree_add=False,
    )


def _real_offtree_state() -> GameState:
    observed = _two_player_state().advance_observed(
        "raise", amount=900,
    ).state
    return replace(observed, real_geometry=True)


def test_real_geometry_forces_exact_extension_when_gate_is_off() -> None:
    engine = _CaptureEngine()
    source = _source(engine)

    source.get_mix(_real_offtree_state(), (40, 36))

    assert len(engine.calls) == 1
    replay = engine.calls[0]["hero_replay"]
    assert "offtree" in replay
    fraction = replay["offtree"]["event_fractions"][0]
    assert _builder_amount(fraction, 600, 0) == 900
    assert replay["offtree"]["expected_event_amounts"] == {0: 900}
    assert source.last_offtree_add is not None
    assert source.last_offtree_add["dropped"] is False


def test_real_geometry_unsafe_extension_fails_without_base_retry() -> None:
    from app.engine.agent.live_resolve_adapter import LiveResolveUnsupported

    engine = _CaptureEngine(unsafe_extension=True)
    source = _source(engine)

    with pytest.raises(
        LiveResolveUnsupported, match="synthetic exact extension failure",
    ):
        source.get_mix(_real_offtree_state(), (40, 36))

    assert len(engine.calls) == 1
    assert "offtree" in engine.calls[0]["hero_replay"]
    assert source.last_offtree_add is not None
    assert source.last_offtree_add["dropped"] is True


def test_real_geometry_refuses_canonical_cont_ev_catalog() -> None:
    from app.engine.agent.live_resolve_adapter import LiveResolveUnsupported

    engine = _CaptureEngine()
    engine.cont_ev_router = object()
    source = _source(engine)

    with pytest.raises(LiveResolveUnsupported, match="cont_ev catalog"):
        source.get_mix(_real_offtree_state(), (40, 36))

    assert engine.calls == []
    assert source.last_offtree_add is not None
    assert source.last_offtree_add["dropped"] is True


